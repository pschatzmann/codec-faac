#!/usr/bin/env python3
"""
Create the Arduino library layout of FAAC from the upstream sources in
original/faac.

The upstream meson build generates a config.h and force-includes it into
every translation unit (-include config.h). The Arduino IDE does not support
force includes, so this script

  * copies include/faac.h            -> src/faac.h
  * copies libfaac/*.c, libfaac/*.h  -> src/libfaac/
  * generates src/libfaac/faac_config.h (replacement for meson's config.h)
  * prepends '#include "faac_config.h"' to every copied .c file
  * guards quantize_sse.c with HAVE_SSE2 (only used on x86 hosts)
  * extracts the ADTS example from docs/libfaac.md for the CMake build
  * writes library.properties

Re-running the script replaces src/ completely. Usage:

    python3 create_arduino_lib.py [--source original/faac] [--dest .]
"""

import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

CONFIG_INCLUDE = '#include "faac_config.h" /* added by create_arduino_lib.py */\n'

# Files of libfaac that are not part of the Arduino library
SKIP_FILES = {"meson.build", "libfaac.def"}

# Top level files copied unchanged
TOP_LEVEL_FILES = ["COPYING", "AUTHORS", "ChangeLog", "NEWS"]


def read_version(source: Path) -> str:
    meson = (source / "meson.build").read_text()
    m = re.search(r"version:\s*'([^']+)'", meson)
    if not m:
        sys.exit("could not determine version from meson.build")
    return m.group(1)


def read_git_revision(source: Path) -> str:
    try:
        return subprocess.check_output(
            ["git", "-C", str(source), "rev-parse", "--short", "HEAD"],
            text=True, stderr=subprocess.DEVNULL).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def config_header(version: str) -> str:
    # Mirrors the configuration_data() of the upstream meson.build. Every value
    # can be overridden with a compiler define (e.g. -DMAX_CHANNELS=8).
    return f"""\
/*
 * FAAC configuration for the Arduino / CMake build.
 * Generated by create_arduino_lib.py - do not edit, re-run the script instead.
 *
 * Replaces the config.h that meson generates and force-includes.
 * All settings can be overridden by defining them before compilation.
 */
#ifndef FAAC_CONFIG_H
#define FAAC_CONFIG_H

#ifndef PACKAGE
#define PACKAGE "faac"
#endif

#ifndef PACKAGE_VERSION
#define PACKAGE_VERSION "{version}"
#endif

/* Maximum number of channels (1-8). Every channel adds several KB of static
 * encoder state, so microcontroller builds default to stereo. */
#ifndef MAX_CHANNELS
#if defined(ARDUINO)
#define MAX_CHANNELS 2
#else
#define MAX_CHANNELS 8
#endif
#endif

/* SBR analysis density: analyse every Nth slot (1 = full quality, max 8).
 * Higher values make HE-AAC encoding faster at a small quality cost. */
#ifndef FAAC_SBR_DECIMATION
#define FAAC_SBR_DECIMATION 1
#endif

/* Define FAAC_STATS to print end-of-encode statistics to stderr. */

#ifndef WORDS_BIGENDIAN
#if defined(__BYTE_ORDER__) && defined(__ORDER_BIG_ENDIAN__) && \\
    (__BYTE_ORDER__ == __ORDER_BIG_ENDIAN__)
#define WORDS_BIGENDIAN 1
#else
#define WORDS_BIGENDIAN 0
#endif
#endif

/* SSE2 quantizer: only on x86 hosts where the compiler targets SSE2 */
#if !defined(HAVE_SSE2) && !defined(FAAC_NO_SSE2) && !defined(ARDUINO) && \\
    (defined(__SSE2__) || defined(_M_X64) || \\
     (defined(_M_IX86_FP) && _M_IX86_FP >= 2))
#define HAVE_SSE2 1
#define HAVE_IMMINTRIN_H 1
#endif

#endif /* FAAC_CONFIG_H */
"""


def library_properties(version: str, revision: str) -> str:
    return f"""\
name=codec-faac
version={version}
author=FAAC authors (see AUTHORS)
maintainer=Phil Schatzmann <phil.schatzmann@gmail.com>
sentence=FAAC - Freeware Advanced Audio Coder: AAC-LC and HE-AAC encoder
paragraph=Arduino port of libfaac (upstream revision {revision}). Encodes PCM to ADTS or raw AAC.
category=Signal Input/Output
url=https://github.com/FreewareAdvancedAudio/faac
architectures=*
includes=faac.h
"""


def copy_c_source(src: Path, dst: Path):
    text = src.read_text()
    if src.name == "quantize_sse.c":
        text = (CONFIG_INCLUDE + "#if defined(HAVE_SSE2)\n\n" + text
                + "\n#endif /* HAVE_SSE2 */\n")
    else:
        text = CONFIG_INCLUDE + text
    dst.write_text(text)


def extract_example(source: Path, dest: Path):
    """Extract the 'Complete ADTS encode example' from docs/libfaac.md."""
    doc = (source / "docs" / "libfaac.md").read_text()
    m = re.search(r"### Complete ADTS encode example.*?```c\n(.*?)```",
                  doc, re.S)
    if not m:
        print("warning: ADTS example not found in docs/libfaac.md")
        return
    out = dest / "examples" / "cmake" / "adts_encode.c"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("/* Extracted from docs/libfaac.md by create_arduino_lib.py */\n"
                   + m.group(1))
    print(f"  {out.relative_to(dest)}")


def main():
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=here / "original" / "faac",
                        help="upstream faac checkout (default: original/faac)")
    parser.add_argument("--dest", type=Path, default=here,
                        help="Arduino library root (default: script directory)")
    args = parser.parse_args()

    source = args.source.resolve()
    dest = args.dest.resolve()
    if not (source / "libfaac").is_dir() or not (source / "include" / "faac.h").is_file():
        sys.exit(f"{source} does not look like a faac source tree")

    version = read_version(source)
    revision = read_git_revision(source)
    print(f"faac {version} ({revision}): {source} -> {dest}")

    src = dest / "src"
    if src.exists():
        shutil.rmtree(src)
    lib = src / "libfaac"
    lib.mkdir(parents=True)

    shutil.copy2(source / "include" / "faac.h", src / "faac.h")

    count = 0
    for f in sorted((source / "libfaac").iterdir()):
        if not f.is_file() or f.name in SKIP_FILES:
            continue
        if f.suffix == ".c":
            copy_c_source(f, lib / f.name)
        elif f.suffix == ".h":
            shutil.copy2(f, lib / f.name)
        else:
            continue
        count += 1
    (lib / "faac_config.h").write_text(config_header(version))
    print(f"  src/faac.h, {count} files in src/libfaac, src/libfaac/faac_config.h")

    for name in TOP_LEVEL_FILES:
        if (source / name).exists():
            shutil.copy2(source / name, dest / name)
    docs = dest / "docs"
    docs.mkdir(exist_ok=True)
    shutil.copy2(source / "docs" / "libfaac.md", docs / "libfaac.md")
    print(f"  {', '.join(TOP_LEVEL_FILES)}, docs/libfaac.md")

    extract_example(source, dest)

    (dest / "library.properties").write_text(library_properties(version, revision))
    print("  library.properties")


if __name__ == "__main__":
    main()
